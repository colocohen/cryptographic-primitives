/**
 * Baby Jubjub  -  an elliptic curve that lives INSIDE a zk circuit
 *
 * A twisted Edwards curve whose base field is BN254's SCALAR field. That one
 * sentence is the whole point, and it takes a moment to see why it matters.
 *
 * ==================== WHY AN "EMBEDDED" CURVE EXISTS ====================
 *
 * A zk circuit computes over one field - for Ethereum's proof systems, BN254's
 * scalar field. Anything the circuit does has to be expressed as arithmetic in
 * THAT field.
 *
 * Now suppose the circuit needs to verify a signature. secp256k1's arithmetic
 * happens modulo a completely different prime, so every multiplication has to
 * be SIMULATED with multi-precision arithmetic inside the circuit - hundreds
 * of constraints for one field multiplication, and millions for one signature.
 *
 * Baby Jubjub sidesteps that: its coordinates ARE elements of the circuit's
 * field, so a point addition is a handful of native multiplications. Verifying
 * an EdDSA signature over it costs a few thousand constraints instead of
 * millions.
 *
 *     "Base field of the curve = scalar field of the proof system"
 *
 * That is the defining relationship, and it is why every proof system has its
 * own embedded curve: Baby Jubjub for BN254, Jubjub for BLS12-381 in Zcash,
 * Grumpkin for Aztec's recursion.
 *
 * IT IS NOT A REPLACEMENT FOR Ed25519. Its security is around 126 bits - a
 * little below the usual target - and it is chosen for circuit cost, not for
 * being the best curve available. Outside a circuit there is no reason to use
 * it.
 *
 * THE COFACTOR IS 8, as with Ed25519, so the same small-subgroup concerns
 * apply: the useful group is the prime-order subgroup generated by Base8,
 * which is the generator scaled by the cofactor.
 */

import { field, BN254_FR } from './commons/modp.js';
import { edwards, subgroup_check, y_sign_codec } from './commons/edwards.js';
import { fixed_base } from './commons/fixed_window.js';
import { bytes_to_bigint_le, bigint_to_bytes_le } from './commons/bytes.js';
import { random_secret_below, key_from_seed } from './commons/group.js';

/**
 * The curve, from EIP-2494.
 *
 *     ax^2 + y^2 = 1 + d x^2 y^2   over BN254's scalar field
 *
 * a = 168700 and d = 168696 are small by design - a smaller coefficient means
 * fewer constraints when the curve equation is checked inside a circuit,
 * which is the same reasoning that shaped every other choice here.
 */
export var CURVE = {
    p: BN254_FR,
    a: 168700n,
    d: 168696n,
    /* the full group order, and the prime-order subgroup */
    order: 21888242871839275222246405745257275088614511777268538073601725287587578984328n,
    sub_order: 2736030358979909402780800718157159386076813972158567259200215660948447373041n,
    cofactor: 8n,
    /* the generator, and the cofactor-cleared generator that protocols use */
    Gx: 995203441582195749578291179787384436505546430278305826713579947235728471134n,
    Gy: 5472060717959818805561601436314318772137091100104008585924551046643952123905n,
    B8x: 5299619240641551281634865583518297030282874472190772894086521144482721001553n,
    B8y: 16950150798460657717958625567821834550301663161624707787222815936182638968203n
};

export var FIELD = /* @__PURE__ */ field(CURVE.p);
export var POINT = /* @__PURE__ */ edwards(FIELD, CURVE.a, CURVE.d);

/** The full generator. Most protocols want BASE8 instead. */
export var GENERATOR = /* @__PURE__ */ POINT.of(CURVE.Gx, CURVE.Gy);

/**
 * The generator of the PRIME-ORDER subgroup - GENERATOR times the cofactor.
 *
 * Use this one. Multiplying the full generator by a scalar can land outside
 * the prime-order subgroup, and every small-subgroup attack this library
 * documents elsewhere applies here too.
 */
export var BASE8 = /* @__PURE__ */ POINT.of(CURVE.B8x, CURVE.B8y);

var SCALAR_BITS = 251;   /* sub_order is 251 bits */

function mod_order(k) {
    var r = k % CURVE.sub_order;
    return r < 0n ? r + CURVE.sub_order : r;
}

/* ---------------- group operations ---------------- */

export function add(P, Q) { return POINT.add(P, Q); }

export function neg(P) { return POINT.neg(P); }

export function sub(P, Q) { return POINT.add(P, POINT.neg(Q)); }

/**
 * k * P.
 *
 * The scalar is NOT reduced here, because a caller may legitimately want a
 * multiple larger than the subgroup order - the ladder width is set from the
 * scalar's own size for that reason.
 */
export function mul(k, P) {
    var bits = k.toString(2).length;
    return POINT.mul(k, P, bits < SCALAR_BITS ? SCALAR_BITS : bits);
}

/**
 * k * BASE8, the operation a key derivation performs.
 *
 * ⭐ THROUGH A PRECOMPUTED TABLE. BASE8 never changes, so its multiples are
 *   computed once at module load and every later call is lookups and
 *   additions rather than SCALAR_BITS doublings.
 *
 * ⛔ IT WAS `mul(mod_order(k), BASE8)` - the generic variable-base routine,
 *   which discards the one fact that makes base multiplication cheap.
 *   Measured before: 1.5 ms, against a generic mul of 2.0 - a ratio of 1.3
 *   where a working table gives 5 or more.
 *
 *   ristretto255 had the same gap and was fixed the same way; the NIST
 *   curves never did, because commons/ecdsa.js builds one.
 *
 * ⚠ mod_order STAYS OUTSIDE THE TABLE. The table is built for
 *   SCALAR_BITS-wide inputs, so a k above the order would index past its
 *   windows - and the reduction is also what makes base_mul(ORDER) and
 *   base_mul(0) agree. Moving it inside would look correct on every small
 *   input and fail only near the order.
 */
var BASE8_TABLE = /* @__PURE__ */ fixed_base(POINT, BASE8, SCALAR_BITS, 4);

export function base_mul(k) { return BASE8_TABLE(mod_order(k)); }

export function eq(P, Q) { return POINT.eq(P, Q); }

export var IDENTITY = /* @__PURE__ */ POINT.ZERO;

/**
 * Whether a point is in the prime-order subgroup.
 *
 * REQUIRED FOR ANY POINT THAT ARRIVED FROM OUTSIDE. A point on the curve but
 * outside the subgroup leaks information about a secret scalar it is
 * multiplied by, which is the small-subgroup attack in its usual form. The
 * check is one scalar multiplication and is worth it.
 */
export var in_subgroup = /* @__PURE__ */ subgroup_check(POINT, CURVE.sub_order);

/** Whether the coordinates satisfy the curve equation at all. */
/* a*x^2 + y^2 == 1 + d*x^2*y^2 - commons/edwards.js already checks exactly
   this for its curve, which is this curve; it was written out here again */
export function is_on_curve(x, y) { return POINT.is_on_curve(x, y); }

/* ---------------- encoding ---------------- */

/*
 * 32 bytes, little-endian y with x's sign in the top bit - the same layout
 * Ed25519 uses, and what circomlib writes.
 *
 * THE SIGN BIT IS "x > p/2", NOT x's PARITY. Ed25519 stores the parity, and
 * this looks like the same encoding, so copying that convention here produces
 * something that round-trips perfectly with itself and disagrees with
 * circomlib on about forty per cent of points - which is exactly what
 * happened while writing this. commons/edwards.js y_sign_codec takes the rule
 * as a parameter; Jubjub, the same layout over BLS12-381, uses the parity.
 *
 * x = 0 with the sign bit set is accepted (strict: false), as circomlib does.
 */
var CODEC = /* @__PURE__ */ y_sign_codec(POINT, { sign: 'half', strict: false });

/** Encode a point. The identity is refused, as by every GROUP in the library. */
export function encode(P) {
    /* ⛔ checked on the POINT: an Edwards to_affine never returns null, so
       the old `A === null` test never fired and the identity encoded as
       y = 1 - unlike every GROUP in the library, which refuses it */
    if (POINT.eq(P, POINT.ZERO)) { throw new Error('babyjubjub: cannot encode the identity'); }
    return CODEC.encode(P);
}

/**
 * Recover a point from its 32-byte encoding.
 *
 * NOT CONSTANT TIME, deliberately: BN254's scalar field is 1 mod 8, so the
 * square root is Tonelli-Shanks, whose iteration count depends on the input.
 * A point being decoded is public by construction.
 *
 * THE SUBGROUP IS NOT CHECKED HERE. Call in_subgroup() on anything that will
 * be multiplied by a secret scalar.
 *
 * @return {object|null} null when the bytes are not a curve point
 */
export var decode = CODEC.decode;

/* ---------------- keys ---------------- */

/**
 * A key pair: { sk: the secret scalar as 32 little-endian bytes (the byte
 * order of this curve's point encoding, and circomlib's), pk: encode(sk·BASE8) }.
 * mul and base_mul take a bigint, so a caller multiplying by the key reads
 * it back little-endian.
 *
 * ⚠ NOT circomlib's EdDSA key, which hashes a 32-byte private key with
 *   BLAKE-512 and prunes it; this is the bare scalar.
 *
 * @param {Uint8Array} [seed]  the scalar's 32 bytes - below sub_order and
 *   nonzero, or refused; omitted or null draws a fresh one from the
 *   platform, uniform in [1, sub_order)
 */
export function keygen(seed) {
    var sk = key_from_seed('babyjubjub.keygen', seed, function () {
        return bigint_to_bytes_le(random_secret_below(CURVE.sub_order, 'babyjubjub.keygen'), 32);
    });
    var k = sk.length === 32 ? bytes_to_bigint_le(sk) : 0n;
    if (k === 0n || k >= CURVE.sub_order) {
        throw new Error('babyjubjub.keygen: the seed must be 32 bytes, a nonzero scalar below sub_order');
    }
    return { sk: sk, pk: encode(base_mul(k)) };
}
