/**
 * Blowfish  -  Schneier, 1993
 *
 * Free of patents from the day it was published, which is why it spread
 * everywhere in the 1990s: OpenSSH, GnuPG, and a long tail of file formats
 * and databases still hold data encrypted with it.
 *
 * 64-bit blocks and a variable key from 4 to 56 bytes. Sixteen Feistel
 * rounds over four 8x8-to-32 S-boxes.
 *
 * THE SAME 64-BIT BLOCK PROBLEM AS 3DES. Birthday collisions among ciphertext
 * blocks start leaking plaintext relationships after about 2^32 blocks - 32 GB
 * under one key - and Sweet32 demonstrated that as a practical attack. The key
 * length is not the issue; the block size is. Schneier himself has said for
 * years to use something else, and he means it.
 *
 * WHAT MAKES IT UNUSUAL: key setup costs 521 block encryptions, because the
 * key is mixed in and then every entry of the P-array and all four S-boxes is
 * re-derived by encrypting a running block. That was a deliberate design
 * choice - expensive setup, cheap encryption - and it is precisely the
 * property bcrypt exploits by running that setup 2^cost times. The machinery
 * is shared through commons/blowfish.js for exactly that reason.
 *
 * Same cache-timing caveat as every table-driven cipher here, and more of it:
 * the S-boxes total 4 KiB and are themselves key-derived.
 */

import { bind_modes } from './commons/cipher_modes.js';
import { blowfish_setup, blowfish_block, P, S } from './commons/blowfish.js';

var BLOCK = 8;

/*
 * The key schedule writes into module-level state shared with bcrypt, so a
 * caller's schedule has to be captured before another key is set up. Copying
 * 4 KiB per cipher instance is the price of not allocating it per block.
 */
function blocks(key, decrypting) {
    if (key.length < 4 || key.length > 56) {
        throw new Error('blowfish: key must be 4 to 56 bytes');
    }
    blowfish_setup(key);
    var p = new Int32Array(P), s = new Int32Array(S);

    return function (src, off, out, out_off) {
        P.set(p); S.set(s);
        blowfish_block(src, off, out, out_off, decrypting);
    };
}

/*
 * ECB, CBC (PKCS#7 unless no_pad; decryption returns null on bad padding) and
 * CTR (the whole 8-byte IV is the counter), generated by
 * commons/cipher_modes.js - the same wrappers DES, 3DES and RC2 use, and which
 * each of them used to write out.
 */
var M = bind_modes('blowfish', BLOCK, blocks);

export var blowfish_ecb_encrypt = M.ecb_encrypt;
export var blowfish_ecb_decrypt = M.ecb_decrypt;
/* ECB under a key set once: encrypt(data), decrypt(data) - see aes.js. */
export var blowfish_ecb_create = M.ecb_create;
export var blowfish_cbc_encrypt = M.cbc_encrypt;
export var blowfish_cbc_decrypt = M.cbc_decrypt;
export var blowfish_ctr = M.ctr;
/* CTR fed in pieces (and keyed AEAD contexts) - see aes.js. */
export var blowfish_ctr_create = M.ctr_create;
