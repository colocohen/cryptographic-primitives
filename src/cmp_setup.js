/**
 * cmp_setup.js - the expensive half of CGGMP21's auxiliary data.
 *
 * A signer needs three things before any protocol round can run: a Paillier
 * keypair, a set of Ring-Pedersen parameters, and proofs that both are well
 * formed. This file makes the first two. It does NOT make the proofs, and the
 * split is the whole point of the file.
 *
 * ==================== WHY IT IS SPLIT ====================
 *
 * Measured here, at 1024 bits:
 *
 *     Paillier with safe primes    24.6 s
 *     Ring-Pedersen parameters      9.0 s
 *     ------------------------------------
 *     one signer                   33.6 s
 *
 *     a whole FROST key generation  0.2 s
 *
 * A hundred and seventy times, and production wants 2048 bits, which is
 * minutes. That is not a number that shapes an optimisation - it shapes an
 * architecture. Key generation that takes minutes is key generation the user
 * believes has hung.
 *
 * The material here is good for the lifetime of the signer. The PROOFS about
 * it are not, and that is the line this file draws:
 *
 *     once, ever      safe primes, Paillier, Ring-Pedersen   <- here
 *     every run       Pi^prm and Pi^mod, bound to a session  <- caller
 *
 * ==================== WHY THE PROOFS NEED A SESSION ====================
 *
 * The statements themselves are timeless. "s lies in the group generated by
 * t" and "N is a product of two primes congruent to 3 mod 4" are true today
 * and true next year, so a stale proof is not a false one.
 *
 * The risk is not staleness, it is TRANSFERABILITY. Without a binding, one
 * party can present another party's proof as its own: the statement stays
 * true and the claim "this modulus is mine, and here is my proof" becomes
 * something anyone who saw it can make. So prove_params and prove_modulus
 * take a `sid`, and the caller builds it from the session, the prover and the
 * verifier - none of which belong here.
 *
 * The reference implementation reaches the same split from the other
 * direction: it generates primes in one call with no execution id, and
 * passes the execution id to the auxiliary-data protocol that proves things
 * about them.
 */

import { keygen as paillier_keygen } from './paillier.js';
import { keygen as rp_keygen } from './ring_pedersen.js';

/**
 * Generate one signer's long-lived auxiliary material.
 *
 * @param {number}   bits     modulus size; 2048 in production, 512 for tests
 * @param {function} rng      (n) -> Uint8Array
 * @param {function} [onProgress]  (stage, attempt) -> void
 *
 *   `onProgress` fires on every prime candidate, tagged with which of the two
 *   stages is running. Something has to, because a caller waiting half a
 *   minute with no output assumes the process has died - and at 2048 bits it
 *   is minutes. The stage names are 'paillier' and 'ring_pedersen'.
 *
 * @return {{paillier: object, ring_pedersen: object}}
 */
export function precompute_aux(bits, rng, onProgress) {
    var paillier = paillier_keygen(bits, rng, {
        safe: true,
        onCandidate: onProgress
            ? function (n) { onProgress('paillier', n); }
            : undefined
    });

    var ring_pedersen = rp_keygen(bits, rng, onProgress
        ? function (n) { onProgress('ring_pedersen', n); }
        : undefined);

    return { paillier: paillier, ring_pedersen: ring_pedersen };
}
