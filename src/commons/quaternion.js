    function bound_parallelogram(lat, radius) {
        var r = lll_dual_reduce_ideal(lat), gd = r[1], Ainv = r[2], U = [[], [], [], []], box = [], i, j, triv = true;
        for (i = 0; i < 4; i++) { for (j = 0; j < 4; j++) { U[i][j] = Ainv[j][i]; } }
        var den = mul(lat.b[0][0], p);
        for (i = 0; i < 4; i++) { box[i] = sqrt_floor(div(mul(gd[i], radius), den)[0]); triv = triv && is0(box[i]); }
        for (i = 0; i < 4; i++) { for (j = 0; j < 4; j++) { U[i][j] = set_bound(U[i][j], bitsize(U[i][j]) + 1); } }
        box = box.map(function (x) { return set_bound(x, bitsize(x) + 1); });
        return [!triv, box, U];
    }
    /* [element, norm / norm(lattice)]: a random lattice element of reduced norm at most radius */
    function sample_from_ball(lat, radius, dom) {
        var G = product_gram(lat), rad = mul2e(radius, 1), bp = bound_parallelogram(lat, rad), box = bp[1], x, tmp;
        if (!bp[0]) { return null; }
        do {
            x = box.map(function (bx) {
                if (is0(bx)) { return ZERO; }
                return set_bound(sub(rand_interval(ZERO, mul2e(bx, 1), dom), bx), bx.n);
            });
            x = m4_eval_t(x, bp[2]);
            tmp = qf_eval(G, x);
        } while (get32(tmp) % 4 === 0 || cmp(tmp, rad) > 0);
        var norm = div2e(tmp, 1);
        var res = qnormalize({ d: lat.d, c: m4_eval(lat.b, x) });
        res = { d: set_bound(res.d, 3), c: res.c };
        var nb = Math.trunc((radius.n + lat.b[0][0].n) / 2) + res.d.n + 3;
        res = { d: res.d, c: res.c.map(function (y) { return set_bound(y, nb); }) };
        return [res, set_bound(norm, radius.n)];
    }
    /* an element of O_0 of norm n (Cornacchia on the remainder after random j, k parts) */
    function represent_integer(n, dom) {
        var bb = P_BITS, temp = sqrt_floor(mul(p, p));
        var counter = set_bound(div(n, temp)[0], bb);
        var sq = set_bound(sub(div(n, p)[0], ONE), bb), bound = sqrt_floor(sq);
        while (!is0(counter)) {
            counter = set_bound(sub(counter, ONE), bb);
            var c2 = rand_interval(ONE, bound, dom), ct = mul(c2, c2);
            temp = sqrt_floor(set_bound(div(sub(n, mul(ct, p)), p)[0], bb));
            if (is0(temp)) { continue; }
            var c3 = rand_interval(ONE, temp, dom);
            ct = set_bound(sub(n, mul(add(ct, mul(c3, c3)), p)), n.n);
            if (probab_prime(ct)) {
                var cr = cornacchia_prime(ct);
                if (cr[0]) {
                    var b2 = Math.trunc(ct.n / 2) + 2;
                    return { d: set(1, 2), c: [set_bound(cr[1], b2), set_bound(cr[2], b2), c2, c3] };
                }
            }
        }
        return null;
    }
