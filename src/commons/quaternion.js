    function initialize_bounds(gen, N, Li, twoe) {
        var om = [Li[0][0], Li[1][0]], li = sum_two_squares(om[0], om[1]), five = set(5, 4);
        var B1 = div2e(mul(N, five), 1), B0 = div2e(N, 1);
        var Ba = div(mul(sub(mul2e(twoe, 3), mul2e(N, 4)), N), p)[0];
        if (cmp(mul(li, Ba), mul2e(B0, 1)) <= 0) { return null; }
        var q = div(B0, li), ab0 = q[0];
        if (!is0(q[1])) { ab0 = add(ab0, ONE); }
        var ab1 = div(B1, li)[0], hb = div2e(Ba, 1);
        if (cmp(ab1, hb) > 0) { ab1 = hb; }
        var cst = set(bitsize(N), 32);
        cst = mul(cst, cst);
        var big = cmp(sub(ab1, ab0), cst) > 0, f = 0;
        if (!big) {
            var g = gcd(om[0], om[1]), ff = set(1, 2), cst2 = mul(cst, cst);
            while (is0(mod(g, five)) && cmp(ff, cst2) < 0) { g = div(g, five)[0]; ff = mul(ff, five); f++; }
            if (f !== 0) {
                om = [div(om[0], ff)[0], div(om[1], ff)[0]];
                var fv = qe(1, 2, 1, 0, 0);
                if (is0(mod(sub(mul2e(om[0], 1), om[1]), five))) { fv.c[1] = neg(fv.c[1]); }
                for (var i = 1; i < f; i++) { var sq = gauss_mul([fv.c[0], fv.c[1]], [fv.c[0], fv.c[1]]); fv.c[0] = sq[0]; fv.c[1] = sq[1]; }
                om = gauss_mul([fv.c[0], fv.c[1]], om);
                gen = qmul(fv, gen);
            }
            ab0 = mul(ff, ab0); ab1 = mul(ff, ab1);
            big = cmp(sub(ab1, ab0), cst) > 0;
        }
        return { ab: [ab0, ab1], omega: om, gen: gen, f: f, big: big };
    }
    function loop_one(gen, N, ab, om, f, big, dom_default) {
        var gom = gcd(om[0], om[1]), tmp = div2e(ab[0], 1), ob0 = sqrt_floor(tmp), k, need = true, ksq, work, t;
        if (!(cmp(mul(ob0, ob0), tmp) === 0) && !odd(ab[0])) { ob0 = add(ob0, ONE); }
        var ob1 = sqrt_floor(ab[1]);
        if (cmp(ob1, set(11, 5)) !== 1) { k = [set(4, 4), set(3, 4)]; need = false; }
        if (cmp(ob1, set(4, 4)) !== 1) { k = [set(2, 3), set(1, 3)]; need = false; }
        if (cmp(ob1, set(2, 3)) !== 1) { k = [set(1, 2), set(0, 2)]; need = false; }
        var kb = Math.trunc((N.n + P_BITS) / 2);
        for (;;) {
            if (need) {
                var k0 = rand_interval(ob0, ob1, dom_default), tb0;
                ksq = mul(k0, k0);
                if (cmp(ab[0], ksq) > 0) {
                    tmp = sub(ab[0], ksq);
                    tb0 = sqrt_floor(tmp);
                    if (cmp(mul(tb0, tb0), tmp) < 0) { tb0 = add(tb0, ONE); }
                } else { tb0 = set(0, 0); }
                var tb1 = sqrt_floor(sub(ab[1], ksq));
                if (cmp(tb0, tb1) > 0) { continue; }
                k = [k0, rand_interval(tb0, tb1, dom_default)];
            }
            if (odd(k[0]) === odd(k[1])) { continue; }
            if (!is1(gcd(k[1], k[0]))) { continue; }
            tmp = add(mul(k[0], k[0]), mul(k[1], k[1]));
            if (!is1(gcd(tmp, big ? N : gom))) { continue; }
            if (odd(k[0])) { k = [k[1], k[0]]; }
            if (f & 1) { k = [neg(k[1]), k[0]]; }
            var gm = gauss_gcd([k[0], neg(k[1])], om), ng = sum_two_squares(gm[0], gm[1]);
            var sk = 2 * k[0].n;
            if (sk < 2 * k[1].n) { sk = 2 * k[1].n; }
            while (!is1(ng)) {
                gm = gauss_mul(gm, gm);
                k = gauss_mul(k, gm);
                k = [set_bound(div(k[0], ng)[0], sk), set_bound(div(k[1], ng)[0], sk)];
                gm = gauss_gcd([k[0], neg(k[1])], om);
                ng = sum_two_squares(gm[0], gm[1]);
            }
            gm = gauss_mul(gm, gm);
            k = gauss_mul(k, gm);
            k = [set_bound(div(k[0], ng)[0], kb), set_bound(div(k[1], ng)[0], kb)];
            work = qe(1, 0, 0, 0, 0);
            work.c[0] = k[0]; work.c[1] = k[1];
            work = qmul(work, gen);
            t = gcd(N, gcd(work.c[0], work.c[1]));
            if (!is1(t)) { continue; }
            break;
        }
        return [work, gauss_mul(k, om)];
    }
    function loop_two(alpha0, r, st0, N, twoe) {
        var deltaN = mul(set(1 + 2 * (odd(r) ? 0 : 1), 3), N), sb = get_short_basis(st0, alpha0, N), R = sb[0];
        var inv = m2_inv_det(R), Rdet = inv[0], Rinv = inv[1], NL = N.n, e = twoe.n;
        var t0 = sb[1].map(function (x) { return set_bound(neg(x), 2 * NL + 10); });
        var lambda = neg(set(1, 2)), rtwo = mul2e(r, 1), tmd = sub(twoe, deltaN), quadN = mul2e(N, 2);
        var bound = sqrt_floor(div(twoe, r)[0]), target, sum, z, cr;
        while (cmp(lambda, bound) <= 0) {
            lambda = set_bound(add(lambda, TWO), 50);
            if (!is1(gcd(lambda, quadN))) { continue; }
            sum = set_bound(sub(tmd, mul(mul(rtwo, lambda), lambda)), e);
            var li = invmod(lambda, quadN)[1];
            var tmp = set_bound(mod(mul(sum, li), quadN), NL + 10);
            var tl = [mod(neg(mul(t0[0], tmp)), quadN), mod(neg(mul(t0[1], tmp)), quadN)];
            target = m2_eval(Rinv, tl);
            target = m2_eval(R, [rounded_div(target[0], Rdet), rounded_div(target[1], Rdet)]);
            target = [set_bound(sub(tl[0], target[0]), 2 * NL + 10), set_bound(sub(tl[1], target[1]), 2 * NL + 10)];
            if (odd(target[0]) === odd(target[1])) { continue; }
            var k = add(sum, deltaN);
            var s2 = add(mul(target[0], alpha0.c[0]), mul(target[1], alpha0.c[1]));
            k = set_bound(div(sub(k, set_bound(mul(s2, lambda), 2 * NL + 20)), N)[0], e);
            z = set_bound(sub(sub(add(k, k), mul(target[1], target[1])), mul(target[0], target[0])), 2 * NL + 10);
            if (z.v < 0n) { continue; }
            if ((get32(z) & 3) === 1 && probab_prime(z)) {
                cr = cornacchia_prime(z);
                if (cr[0]) {
                    return { l: lambda, s: set_bound(target[0], NL + 10), t: set_bound(target[1], NL + 10), sc: cr[1], tc: cr[2] };
                }
            }
        }
        return null;
    }
    function normeq(I, dom_default) {
        var se = shortest_equivalent(I, dom_default), smallest = se[0], small = se[1];
        small = { n: set_bound(small.n, Math.trunc(P_BITS / 2) + 10), x: small.x, y: small.y };
        var gen = odd_inert_gen(small), N = small.n;
        gen = { d: set_bound(gen.d, 3), c: [set_bound(gen.c[0], N.n), set_bound(gen.c[1], N.n), set_bound(gen.c[2], 2), set_bound(gen.c[3], 1)] };
        var Li = gen_to_dim2(gen, N, false)[0];
        Li = lll_dim2_short_basis([[Li[0][1], Li[0][0]], [Li[1][1], Li[1][0]]], N.n + 2);
        var twoe = mul2e(ONE, P.qlapoty_power), ib = initialize_bounds(gen, N, Li, twoe);
        if (!ib) { return null; }
        var l1 = loop_one(ib.gen, N, ib.ab, ib.omega, ib.f, ib.big, dom_default), alpha0 = l1[0];
        var r = div(qnorm(alpha0)[0], N)[0];
        var l2 = loop_two(alpha0, r, l1[1], N, twoe);
        if (!l2) { return null; }
        var sc = l2.sc, tc = l2.tc;
        if (odd(l2.s) !== odd(sc)) { var t = sc; sc = tc; tc = t; }
        var mu1 = qe(2, 0, 0, 0, 0), mu2 = qe(2, 0, 0, 0, 0);
        mu1.c[0] = add(l2.s, sc); mu1.c[1] = add(l2.t, tc); mu2.c[0] = sub(l2.s, sc); mu2.c[1] = sub(l2.t, tc);
        var temp = qscalar(l2.l, alpha0);
        mu1 = qadd(qscalar(N, mu1), temp);
        mu2 = qadd(qscalar(N, mu2), temp);
        temp = qconj(mu1);
        temp = { d: mul(temp.d, N), c: temp.c };
        return { mu1: mu1, theta: qmul(mu2, temp), smallest: smallest };
    }
    /* [beta1, d1, theta] for the ideal, as the reference's qlapoty */
    function qlapoty(I, dom_default) {
        var ne = normeq(I, dom_default);
        if (!ne) { return null; }
        var theta = qconj(qnormalize(ne.theta));
        var n = set_bound(div(qnorm(ne.smallest)[0], I.n)[0], Math.trunc(P_BITS / 2) + 1);
        var d1 = set_bound(div(qnorm(ne.mu1)[0], n)[0], P.qlapoty_power + 2);
        var beta1 = qmul(ne.mu1, ne.smallest);
        beta1 = qnormalize({ d: mul(beta1.d, n), c: beta1.c });
        var bb = Math.trunc((I.n.n + d1.n) / 2) + 3;
        beta1 = { d: set_bound(beta1.d, 3), c: beta1.c.map(function (x) { return set_bound(x, bb); }) };
        var tb = 2 * (beta1.c[0].n + 1);
        theta = { d: set_bound(theta.d, 4), c: theta.c.map(function (x) { return set_bound(x, tb); }) };
        return [beta1, d1, theta];
    }
    /* [sk_chall_ideal, resp_quat, norm, sk_chall_quat], the signer's response element */
    function response_element(sk_ideal, chall_ideal, chall_split, commit_ideal, dom, dom_default, e) {
        var skc = intersect_O0(chall_ideal, sk_ideal, chall_split);
        var se = small_equivalent_coprime(skc, ZERO, dom_default, true);
        var prod = mul_O0(se[1], commit_ideal);
        var bound = set_bound(sub(mul2e(ONE, e), ONE), e + 1);
        var s = sample_from_ball(prod, bound, dom);
        return [se[1], s[0], set_bound(s[1], e + 1), qconj(se[0])];
    }

