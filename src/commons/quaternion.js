    function materialise(Dk, Dk1, mu) {
        var bf = highmul_p(mu, Dk, PB, LDL_W), cf = asb(Dk1, highmul_p(mu, bf, PB, LDL_W), LDL_W);
        var e = max0(bitsize(asb(Dk, cf, LDL_W + 1)) - (GRAM_TOT - 1));
        return { a: ct_shift(Dk, -e, LDL_W + 1, GRAM_TOT), b: ct_shift(bf, -e, LDL_W + 1, GRAM_TOT), c: ct_shift(cf, -e, LDL_W + 1, GRAM_TOT) };
    }
    function fast_log2_ratio(a, b, clz_b) {
        var clz_a = clz64(a | 1n), na = shl64(a, clz_a) >> 2n, nb = shl64(b, clz_b) >> 2n, tb = u64(3n * nb);
        return (clz_b - clz_a) + (shl64(na, 1) >= tb ? 1 : 0) - (shl64(na, 2) < tb ? 1 : 0);
    }
    function partial_gram_msb(a, b, c, swap) {
        var u00 = 1, u01 = 0, u10 = 0, u11 = 1, valid = M64, gs = mask64(swap), t;
        for (var i = 0; i < Math.floor(LG_T / 2) + 2; i++) {
            valid &= ~mask64(a === 0n || c === 0n) & M64;
            var negm = (b < 0n) && valid !== 0n, ba = abs64(b);
            b = ba;
            if (negm) { u00 = -u00 | 0; u10 = -u10 | 0; }
            var sm = mask64(c < a) & valid;
            valid &= (~sm | gs) & M64;
            if (sm & gs) { t = a; a = c; c = t; t = u00; u00 = u01; u01 = t; t = u10; u10 = u11; u11 = t; }
            valid &= ~mask64(u64(2n * ba) <= a) & M64;
            var cla = clz64(a | 1n), clc = clz64(c | 1n);
            valid &= ~mask64(cla >= 64 - LG_EW + LG_T || clc >= 64 - LG_EW + LG_T) & M64;
            var k = fast_log2_ratio(ba, a, cla);
            if (k < 0) { k = 0; }
            c = u64(c - (u64(shl64(ba, k + 1) - shl64(a, 2 * k)) & valid));
            b = i64(b - (shl64(a, k) & valid));
            var v32 = valid ? -1 : 0;
            u01 = (u01 - (shl32(u00, k) & v32)) | 0;
            u11 = (u11 - (shl32(u10, k) & v32)) | 0;
        }
        return [[u00, u01], [u10, u11]];
    }
    function gram_lehmer(g, iters) {
        var U = [[set_bound(set(1, 2), U_BITS), set_bound(set(0, 2), U_BITS)], [set_bound(set(0, 2), U_BITS), set_bound(set(1, 2), U_BITS)]];
        var a = set_bound(g.a, GRAM_WORK), b = set_bound(g.b, GRAM_WORK), c = set_bound(g.c, GRAM_WORK), t, w = GRAM_WORK;
        for (var i = 0; i < iters; i++) {
            if (c.v - a.v < 0n) { t = a; a = c; c = t; t = U[0][0]; U[0][0] = U[0][1]; U[0][1] = t; t = U[1][0]; U[1][0] = U[1][1]; U[1][1] = t; }
            var bits_a = bitsize(a), bits_c = bitsize(c), rho = bits_c - bits_a, large = rho >= LG_T;
            var bfc = Math.max(bits_c - LG_EW, 0), extra = large ? Math.trunc((rho - LG_T + 2) / 2) : 0;
            var bfa = large ? bfc - 2 * extra : bfc, bfb = large ? bfc - extra : bfc;
            var M = partial_gram_msb(extract_u64(a, bfa), extract_i64(b, bfb), extract_u64(c, bfc), !large);
            var m00 = M[0][0], m01 = M[0][1], m10 = M[1][0], m11 = M[1][1];
            var ca0 = Math.imul(m00, m00), ca1 = Math.imul(Math.imul(2, m00), m10), ca2 = Math.imul(m10, m10);
            var cb0 = Math.imul(m00, m01), cb1 = (Math.imul(m00, m11) + Math.imul(m01, m10)) | 0, cb2 = Math.imul(m10, m11);
            var cc0 = Math.imul(m01, m01), cc1 = Math.imul(Math.imul(2, m01), m11), cc2 = Math.imul(m11, m11);
            var na = asb(asb(mbi(a, ca0, w), mbi(b, ca1, w), w), mbi(c, ca2, w), w);
            var ash = ct_shl(a, extra, LG_ESM, w), bsh = ct_shl(b, extra, LG_ESM, w);
            var nb_ = asb(asb(mbi(ash, cb0, w), mbi(b, cb1, w), w), mbi(c, cb2, w), w);
            ash = ct_shl(a, 2 * extra, 2 * LG_ESM, w);
            var nc = asb(asb(mbi(ash, cc0, w), mbi(bsh, cc1, w), w), mbi(c, cc2, w), w);
            a = na; b = nb_; c = nc;
            var nu00 = asb(mbi(U[0][0], m00, U_BITS), mbi(U[0][1], m10, U_BITS), U_BITS);
            var nu10 = asb(mbi(U[1][0], m00, U_BITS), mbi(U[1][1], m10, U_BITS), U_BITS);
            var nu01 = asb(mbi(ct_shl(U[0][0], extra, LG_ESM, U_BITS), m01, U_BITS), mbi(U[0][1], m11, U_BITS), U_BITS);
            var nu11 = asb(mbi(ct_shl(U[1][0], extra, LG_ESM, U_BITS), m01, U_BITS), mbi(U[1][1], m11, U_BITS), U_BITS);
            U = [[nu00, nu01], [nu10, nu11]];
        }
        return U.map(function (r) { return r.map(function (x) { return set_bound(x, U_BITS); }); });
    }
