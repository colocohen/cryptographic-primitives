/**
 * paillier_range_exact.js - a Paillier plaintext lies in [a, b] EXACTLY.
 *
 *     common input (N0, C, a, b) and the verifier's ring-Pedersen (Nhat, s, t);
 *     the prover knows (x, rho) with  C = (1+N0)^x rho^N0 mod N0^2,  a <= x <= b
 *
 * Pi^enc (paillier_range.js) proves |x| < 2^(ell+eps): a range WITH SLACK,
 * about eps bits wider than the honest one. That is enough to stop a modulus
 * wrapping, and not enough where the protocol's functionality states an
 * exact bound - F_RSAGen (eprint 2020/370, Functionality 3.8) accepts the
 * adversary's shares only if 0 <= p_i < M.
 *
 * ==================== THE CONSTRUCTION ====================
 *
 * The three-square range proof (3SRP) of Couteau, Peters, Pointcheval,
 * "Removing the Strong RSA Assumption from Arguments over the Integers",
 * eprint 2016/128, Figure 2 (section 7.2), on Damgard-Fujisaki commitments -
 * which ARE ring-Pedersen commitments: g = s, h = t, n = Nhat, generated by
 * the verifier with s in <t> (ring_pedersen.js, Pi^prm). The idea (Groth
 * 2005): a <= x <= b iff 4(x - a)(b - x) + 1 >= 1 is a sum of three squares.
 *
 *     c = g^x h^r,  c0 = c^-1 g^b  (opens x0 = b - x, r0 = -r),
 *     ca = (c g^-a)^4,  c_i = g^x_i h^r_i  with  sum x_i^2 = 4(x - a)(b - x) + 1
 *
 * and a Sigma protocol for knowledge of openings of c0..c3 plus the relation
 *
 *     ca^x0 * g * prod c_i^-x_i = h^rho*,   rho* = 4 r x0 - sum x_i r_i
 *
 * which says 4(x - a)(b - x) + 1 = sum x_i^2 over the integers.
 *
 * ⛔ FIGURE 2 PRINTS THE LAST RESPONSE WRONG: tau = sigma + e(x0 r0 -
 *   sum x_i r_i). With the figure's own check h^tau g^e ca^z0 prod c_i^-z_i
 *   = h^sigma ca^m0 prod c_i^-m_i, expanding gives
 *
 *       tau = sigma - e rho* = sigma + e(4 x0 r0 + sum x_i r_i)
 *
 *   - the factor 4 comes from ca = (c g^-a)^4 (its randomiser is 4r), and the
 *   sign of the sum from c_i^-x_i. The printed one fails for every honest
 *   prover; the test file checks the derived one.
 *
 * THE LINK TO PAILLIER is one more equation on the response z0 that the
 * 3SRP already has: C0 = C^-1 (1+N0)^b encrypts x0 = b - x under
 * randomiser rho^-1, so with A0 = (1+N0)^m0 rA^N0,
 *
 *     (1+N0)^z0 w^N0 = A0 C0^e  mod N0^2,   w = rA rho^-e
 *
 * - the same pattern as Pi^enc's Paillier-to-ring-Pedersen link. From two
 * transcripts, x0 is extracted over the integers on the ring-Pedersen side
 * (0 <= x0 <= b - a, by the three squares) and C0's plaintext is x0 mod N0,
 * so C's plaintext is b - x0 in [a, b] (taken mod N0, which is why |a|, |b|
 * must stay below N0/2).
 *
 * WHAT DIFFERS FROM FIGURE 2, beyond tau:
 *   - Fiat-Shamir over every first-message element (no hash-compressed Delta);
 *   - the randomisers r, r_i are drawn from [0, Nhat 2^kappa), not [0, n]:
 *     not needed for hiding ([0, Nhat] reduced mod p'q' is already within
 *     about 2^(-|Nhat|/2) of uniform, since Nhat = 4p'q' + 2(p'+q') + 1), but
 *     it makes the hiding argument independent of Nhat's form. The masks s_i
 *     and sigma are widened to match, each kappa bits above what it hides;
 *   - the responses are bounded (z_i, t_i, tau), so a verifier never
 *     exponentiates by a number the honest range cannot produce.
 *
 * ⚠ THE THREE SQUARES ARE FOUND BY A SEARCH WHOSE LENGTH DEPENDS ON THE
 *   WITNESS (primes.sum_of_three_squares: n = 4(x - a)(b - x) + 1, and the
 *   expected number of draws depends on n mod small primes - in review,
 *   806 vs 346 rng calls on average for n = 1 vs 2 mod 3; an endpoint makes
 *   n a square and returns at once). Proving the SAME x to many verifiers -
 *   n-party RSA key generation does - would multiply the samples, so
 *   range_squares(x, a, b, rng) computes the decomposition once and
 *   opts.squares reuses it: safe, because every commitment to it is freshly
 *   randomised.
 *
 * ⛔ NO EXTERNAL ORACLE.
 */

import { mod, powmod, powmod_signed, powmod_signed_ct, powmod_signed_blind, unit_in,
         random_unit, random_below_biased, sum_of_three_squares, require_rng } from './commons/primes.js';
import { fs_stream, fs_uint, require_sid, paillier_kappa,
         encode_proof, decode_proof } from './commons/zk_bytes.js';
import { enc_raw } from './paillier.js';

var TAG = 'cryptographic-primitives/paillier-range-exact/v1';
var INTS = ['c', 'c1', 'c2', 'c3', 'd0', 'd1', 'd2', 'd3', 'd', 'A0',
            'z0', 'z1', 'z2', 'z3', 't0', 't1', 't2', 't3', 'tau', 'w'];

function bits(v) { return (v < 0n ? -v : v).toString(2).length; }

function params(pk, aux, a, b, opts) {
    var kappa = paillier_kappa('paillier_range_exact', opts, [pk.n]);
    if (typeof a !== 'bigint' || typeof b !== 'bigint' || a > b) {
        throw new Error('paillier_range_exact: the interval [a, b] must be bigints with a <= b');
    }
    var halfN = pk.n >> 1n;
    if (a <= -halfN || b >= halfN) { throw new Error('paillier_range_exact: [a, b] must lie inside +-N0/2'); }
    var B = bits(b - a) + 1;                  /* x0 <= b - a, x_i <= b - a + 1: both below 2^B */
    var R = aux.N << BigInt(kappa);           /* randomiser bound, Nhat 2^kappa */
    return {
        kappa: kappa, B: B, R: R,
        M:  1n << BigInt(B + 2 * kappa),                 /* m_i: kappa above e x_i */
        Sm: R << BigInt(2 * kappa),                      /* s_i: kappa above e r_i */
        Sg: R << BigInt(B + 2 * kappa + 3)               /* sigma: kappa above e rho* */
    };
}

function challenge(pk, aux, C, a, b, pr, P, sid) {
    var parts = [pk.n, aux.N, aux.s, aux.t, C, a, b, BigInt(P.kappa)];
    for (var i = 0; i < 10; i++) { parts.push(pr[INTS[i]]); }
    return fs_uint(fs_stream(TAG, sid, parts), P.kappa);
}

/**
 * The three squares for x in [a, b], to compute once and pass as
 * opts.squares to every proof of the same x (see the header).
 *
 * @return {Array<bigint>} [x1, x2, x3], sum of squares 4(x - a)(b - x) + 1
 */
export function range_squares(x, a, b, rng) {
    if (typeof x !== 'bigint' || x < a || x > b) { throw new Error('paillier_range_exact: x is outside [a, b]'); }
    return sum_of_three_squares(4n * (x - a) * (b - x) + 1n, rng);
}

/**
 * @param {object} pk    the PROVER's Paillier key {n}
 * @param {object} aux   the VERIFIER's ring-Pedersen parameters {N, s, t}
 * @param {bigint} C     enc(x; rho) under pk
 * @param {bigint} x     the plaintext, a <= x <= b
 * @param {bigint} rho   C's randomiser
 * @param {bigint} a, b  the interval, public
 * @param {function} rng
 * @param {object} opts   { factor_bits (REQUIRED, the prover's N0 - see zk_bytes.paillier_kappa),
 *                          kappa (default 128), squares (from range_squares, to reuse) }
 * @param {Uint8Array} sid
 */
export function prove_range_exact(pk, aux, C, x, rho, a, b, rng, opts, sid) {
    require_sid('paillier_range_exact', sid);
    rng = require_rng('prove_range_exact', rng);
    var P = params(pk, aux, a, b, opts);
    if (typeof x !== 'bigint' || x < a || x > b) { throw new Error('paillier_range_exact: x is outside [a, b]'); }
    var N0 = pk.n, N02 = N0 * N0, n = aux.N, g = aux.s, h = aux.t;
    if (enc_raw(N0, N02, x, rho) !== mod(C, N02)) { throw new Error('paillier_range_exact: C is not enc(x; rho)'); }

    var xs = (opts && opts.squares) || range_squares(x, a, b, rng);
    if (xs.length !== 3 || xs[0] * xs[0] + xs[1] * xs[1] + xs[2] * xs[2] !== 4n * (x - a) * (b - x) + 1n) {
        throw new Error('paillier_range_exact: opts.squares is not a decomposition for this x and [a, b]');
    }
    var x0 = b - x;
    var r = random_below_biased(P.R, rng), r0 = -r;
    var rs = [random_below_biased(P.R, rng), random_below_biased(P.R, rng), random_below_biased(P.R, rng)];

    var Bb = P.B + 1, Rb = bits(P.R) + 1;    /* ladder widths of the secret exponents */
    function com(v, vb, w, wb) {
        return mod(powmod_signed_ct(g, v, n, vb) * powmod_signed_ct(h, w, n, wb), n);
    }
    var c = com(x - a, Bb, r, Rb);            /* g^x h^r = g^(x-a) h^r * g^a: the public part outside the ladder */
    c = mod(c * powmod_signed(g, a, n), n);
    var ci = [com(xs[0], Bb, rs[0], Rb), com(xs[1], Bb, rs[1], Rb), com(xs[2], Bb, rs[2], Rb)];
    var ca = powmod(mod(c * powmod_signed(g, -a, n), n), 4n, n);

    var m = [], sm = [];
    for (var i = 0; i < 4; i++) { m.push(random_below_biased(P.M, rng)); sm.push(random_below_biased(P.Sm, rng)); }
    var sigma = random_below_biased(P.Sg, rng);
    var Mb = bits(P.M), Smb = bits(P.Sm), Sgb = bits(P.Sg);
    var d = [];
    for (i = 0; i < 4; i++) { d.push(com(m[i], Mb, sm[i], Smb)); }
    var dd = mod(powmod_signed_ct(h, sigma, n, Sgb) * powmod_signed_ct(ca, m[0], n, Mb), n);
    for (i = 0; i < 3; i++) { dd = mod(dd * powmod_signed_ct(ci[i], -m[i + 1], n, Mb), n); }
    var rA = random_unit(N0, rng);
    var A0 = enc_raw(N0, N02, m[0], rA);

    var pr = { c: c, c1: ci[0], c2: ci[1], c3: ci[2], d0: d[0], d1: d[1], d2: d[2], d3: d[3], d: dd, A0: A0 };
    var e = challenge(pk, aux, C, a, b, pr, P, sid);

    var X = [x0, xs[0], xs[1], xs[2]], Rr = [r0, rs[0], rs[1], rs[2]];
    for (i = 0; i < 4; i++) { pr['z' + i] = e * X[i] + m[i]; pr['t' + i] = e * Rr[i] + sm[i]; }
    /* tau = sigma + e (4 x0 r0 + sum x_i r_i) - see the header: not Figure 2's */
    pr.tau = sigma + e * (4n * x0 * r0 + xs[0] * rs[0] + xs[1] * rs[1] + xs[2] * rs[2]);
    /* w = rA rho^-e: the inverse of a randomiser that opens C, blinded */
    pr.w = mod(rA * powmod_signed_blind(rho, -e, N0, rng), N0);
    return pr;
}

/** @return {boolean} */
export function verify_range_exact(pk, aux, C, a, b, proof, opts, sid) {
    require_sid('paillier_range_exact', sid);
    if (!proof) { return false; }
    var P = params(pk, aux, a, b, opts);
    try {
        var i;
        for (i = 0; i < INTS.length; i++) { if (typeof proof[INTS[i]] !== 'bigint') { return false; } }
        var N0 = pk.n, N02 = N0 * N0, n = aux.N, g = aux.s, h = aux.t;
        if (!unit_in(C, N02) || !unit_in(proof.A0, N02) || !unit_in(proof.w, N0)) { return false; }
        var rp = ['c', 'c1', 'c2', 'c3', 'd0', 'd1', 'd2', 'd3', 'd'];
        for (i = 0; i < rp.length; i++) { if (!unit_in(proof[rp[i]], n)) { return false; } }

        /* response bounds: what an honest prover can produce, no more */
        var E = 1n << BigInt(P.kappa);
        var zmax = P.M + E * (1n << BigInt(P.B));
        var tmax = P.Sm + E * P.R;
        var taumax = P.Sg + E * (P.R << BigInt(P.B + 3));
        for (i = 0; i < 4; i++) {
            if (proof['z' + i] < 0n || proof['z' + i] >= zmax) { return false; }
            if (proof['t' + i] <= -tmax || proof['t' + i] >= tmax) { return false; }
        }
        if (proof.tau <= -taumax || proof.tau >= taumax) { return false; }

        var e = challenge(pk, aux, C, a, b, proof, P, sid);

        var c0 = mod(powmod_signed(proof.c, -1n, n) * powmod_signed(g, b, n), n);
        var ca = powmod(mod(proof.c * powmod_signed(g, -a, n), n), 4n, n);
        var cs = [c0, proof.c1, proof.c2, proof.c3];
        /* g^z_i h^t_i = d_i c_i^e */
        for (i = 0; i < 4; i++) {
            if (mod(powmod(g, proof['z' + i], n) * powmod_signed(h, proof['t' + i], n), n) !==
                mod(proof['d' + i] * powmod(cs[i], e, n), n)) { return false; }
        }
        /* h^tau g^e ca^z0 prod c_i^-z_i = d */
        var lhs = mod(powmod_signed(h, proof.tau, n) * powmod(g, e, n), n);
        lhs = mod(lhs * powmod(ca, proof.z0, n), n);
        for (i = 1; i < 4; i++) { lhs = mod(lhs * powmod_signed(cs[i], -proof['z' + i], n), n); }
        if (lhs !== proof.d) { return false; }

        /* the link: (1+N0)^z0 w^N0 = A0 C0^e, C0 = C^-1 (1+N0)^b */
        var C0 = mod(powmod_signed(C, -1n, N02) * enc_raw(N0, N02, b, 1n), N02);
        return enc_raw(N0, N02, proof.z0, proof.w) === mod(proof.A0 * powmod(C0, e, N02), N02);
    } catch (err) {
        return false;
    }
}

/* ---------------- serialisation ---------------- */

export function encode_range_exact(proof) { return encode_proof(proof, INTS, []); }

/** @return {object|null} null if the encoding is malformed */
export function decode_range_exact(bytes) { return decode_proof(bytes, INTS, [], []); }
